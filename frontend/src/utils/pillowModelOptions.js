/**
 * 取得枕頭型號分類列表
 * @returns {string[]} 分類名稱陣列
 */
export const getPillowModelCategories = () => {
    const categories = [...new Set(PILLOW_MODEL_OPTIONS.map(option => option.category))];
    return categories;
};

/**
 * 依分類取得枕頭型號選項
 * @param {string} category - 分類名稱
 * @returns {Array} 該分類的型號選項
 */
export const getPillowModelsByCategory = (category) => {
    if (!category) return PILLOW_MODEL_OPTIONS;
    return PILLOW_MODEL_OPTIONS.filter(option => option.category === category);
};

